import { expect, test } from '@playwright/test'

test('filtros combinados, preço e página seguem a URL e o histórico', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const catalog = page.getByRole('region', { name: 'Catálogo de NFTs' })
  const filters = page.getByRole('complementary', { name: 'Filtros do catálogo' })
  await expect(catalog.locator('article')).toHaveCount(6)
  await page.getByRole('navigation', { name: 'Paginação do catálogo' }).getByRole('button', { name: 'Página 2' }).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(catalog.locator('article')).toHaveCount(3)
  await filters.getByRole('button', { name: /Arte digital/ }).click()
  await expect(page).toHaveURL(/category=Arte/)
  await expect(page).toHaveURL(/page=1/)
  await expect(catalog.locator('article')).toHaveCount(3)
  await filters.getByRole('button', { name: /Ethereum/ }).click()
  await expect(catalog.locator('article')).toHaveCount(2)
  await filters.getByRole('spinbutton', { name: 'Mín. ETH' }).fill('1')
  await filters.getByRole('spinbutton', { name: 'Máx. ETH' }).fill('1.5')
  await filters.getByRole('button', { name: 'Aplicar' }).click()
  await expect(catalog.locator('article')).toHaveCount(1)
  await expect(catalog.getByText('Emerald Ape #042')).toBeVisible()
  await page.reload()
  await expect(catalog.locator('article')).toHaveCount(1)
  await expect(filters.getByRole('button', { name: /Ethereum/ })).toHaveAttribute('aria-pressed', 'true')
  await page.goBack()
  await expect(catalog.locator('article')).toHaveCount(2)
  await expect(filters.getByRole('spinbutton', { name: 'Máx. ETH' })).toHaveValue('')
})

test('busca, ordenação e resultado vazio usam a API', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const catalog = page.getByRole('region', { name: 'Catálogo de NFTs' })
  await page.getByRole('searchbox', { name: 'Buscar NFTs' }).fill('Golden')
  const response = page.waitForResponse((item) => item.url().includes('/api/nfts?') && item.url().includes('q=Golden'))
  await page.getByRole('button', { name: 'Buscar' }).click()
  expect((await (await response).json()).total).toBe(3)
  await expect(catalog.locator('article')).toHaveCount(3)
  await page.getByRole('combobox', { name: 'Ordenar NFTs' }).selectOption('price_desc')
  await expect(catalog.locator('article h3').first()).toHaveText('Golden Beat #207')
  await page.getByRole('searchbox', { name: 'Buscar NFTs' }).fill('nenhum-nft-existe')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await expect(catalog.getByText('Nenhum NFT encontrado para estes filtros.')).toBeVisible()
  await expect(catalog.locator('article')).toHaveCount(0)
})

test('erro com retry e resposta antiga não substitui a busca atual', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.evaluate(() => sessionStorage.setItem('kurio-demo-catalog-error-v1', '1'))
  await page.getByRole('searchbox', { name: 'Buscar NFTs' }).fill('Ape')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await expect(page.getByText('Erro ao carregar os NFTs.')).toBeVisible()
  await page.evaluate(() => sessionStorage.removeItem('kurio-demo-catalog-error-v1'))
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  const catalog = page.getByRole('region', { name: 'Catálogo de NFTs' })
  await expect(catalog.locator('article')).toHaveCount(1)
  await page.evaluate(() => sessionStorage.setItem('kurio-demo-catalog-delay-q-v1', 'Golden'))
  await page.getByRole('searchbox', { name: 'Buscar NFTs' }).fill('Golden')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await expect(page).toHaveURL(/q=Golden/)
  await page.getByRole('searchbox', { name: 'Buscar NFTs' }).fill('Ape')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await expect(page).toHaveURL(/q=Ape/)
  await expect(catalog.locator('article h3')).toHaveText(['Emerald Ape #042'])
  await page.waitForTimeout(750)
  await expect(catalog.locator('article h3')).toHaveText(['Emerald Ape #042'])
})

test('filtros e busca funcionam no mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Abrir filtros' }).click()
  const filters = page.getByRole('complementary', { name: 'Filtros do catálogo' })
  await filters.getByRole('button', { name: /Polygon/ }).click()
  const catalog = page.getByRole('region', { name: 'Catálogo de NFTs' })
  await expect(catalog.locator('article')).toHaveCount(1)
  await page.getByRole('searchbox', { name: 'Explorar coleções' }).fill('Neon')
  await page.getByRole('searchbox', { name: 'Explorar coleções' }).press('Enter')
  await expect(catalog.getByText('Neon Vessel #552')).toBeVisible()
  await page.reload()
  await expect(catalog.getByText('Neon Vessel #552')).toBeVisible()
})
